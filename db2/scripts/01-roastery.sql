CREATE VIEW ROAST_LOT_OVERVIEW AS
SELECT
    l.LOT_CODE,
    f.FARM_NAME,
    f.COUNTRY,
    l.VARIETY,
    l.PROCESSING_METHOD,
    r.ROAST_ID,
    p.PROFILE_NAME,
    r.ROASTED_AT,
    c.SCORE AS CUPPING_SCORE
FROM COFFEE_LOTS l
JOIN FARMS f ON f.FARM_ID = l.FARM_ID
JOIN ROAST_RUNS r ON r.LOT_ID = l.LOT_ID
JOIN ROAST_PROFILES p ON p.PROFILE_ID = r.PROFILE_ID
LEFT JOIN CUPPING_SESSIONS c ON c.ROAST_ID = r.ROAST_ID;
