-- ROASTERY is a fictional specialty-coffee production and traceability database.
CREATE SCHEMA ROASTERY AUTHORIZATION DB2INST1;
SET CURRENT SCHEMA = ROASTERY;

CREATE TABLE FARMS (
    FARM_ID INTEGER NOT NULL PRIMARY KEY,
    FARM_NAME VARCHAR(100) NOT NULL,
    REGION VARCHAR(100) NOT NULL,
    COUNTRY VARCHAR(60) NOT NULL,
    ALTITUDE_MIN_M INTEGER NOT NULL,
    ALTITUDE_MAX_M INTEGER NOT NULL
);

CREATE TABLE COFFEE_LOTS (
    LOT_ID INTEGER NOT NULL PRIMARY KEY,
    FARM_ID INTEGER NOT NULL REFERENCES FARMS (FARM_ID),
    LOT_CODE VARCHAR(24) NOT NULL UNIQUE,
    VARIETY VARCHAR(80) NOT NULL,
    PROCESSING_METHOD VARCHAR(40) NOT NULL,
    HARVEST_YEAR SMALLINT NOT NULL,
    GREEN_WEIGHT_KG DECIMAL(8,2) NOT NULL
);

CREATE TABLE ROAST_PROFILES (
    PROFILE_ID INTEGER NOT NULL PRIMARY KEY,
    PROFILE_NAME VARCHAR(80) NOT NULL UNIQUE,
    CHARGE_TEMP_C DECIMAL(5,1) NOT NULL,
    TARGET_DEVELOPMENT_SECONDS INTEGER NOT NULL,
    DESCRIPTION VARCHAR(300) NOT NULL
);

CREATE TABLE ROAST_RUNS (
    ROAST_ID INTEGER NOT NULL PRIMARY KEY,
    LOT_ID INTEGER NOT NULL REFERENCES COFFEE_LOTS (LOT_ID),
    PROFILE_ID INTEGER NOT NULL REFERENCES ROAST_PROFILES (PROFILE_ID),
    ROASTED_AT TIMESTAMP NOT NULL,
    GREEN_INPUT_KG DECIMAL(6,2) NOT NULL,
    ROASTED_OUTPUT_KG DECIMAL(6,2) NOT NULL,
    OPERATOR VARCHAR(80) NOT NULL
);

CREATE TABLE CUPPING_SESSIONS (
    CUPPING_ID INTEGER NOT NULL PRIMARY KEY,
    ROAST_ID INTEGER NOT NULL REFERENCES ROAST_RUNS (ROAST_ID),
    TASTER VARCHAR(80) NOT NULL,
    SCORE DECIMAL(4,1) NOT NULL CHECK (SCORE BETWEEN 0 AND 100),
    TASTING_NOTES VARCHAR(500) NOT NULL,
    TASTED_AT DATE NOT NULL
);

CREATE TABLE WHOLESALE_ORDERS (
    ORDER_ID INTEGER NOT NULL PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(120) NOT NULL,
    ROAST_ID INTEGER NOT NULL REFERENCES ROAST_RUNS (ROAST_ID),
    ORDERED_AT DATE NOT NULL,
    BAGS_1KG INTEGER NOT NULL CHECK (BAGS_1KG > 0),
    STATUS VARCHAR(20) NOT NULL
);

