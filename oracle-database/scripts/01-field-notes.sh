#!/usr/bin/env bash
set -euo pipefail

: "${FIELD_NOTES_PASSWORD:=FieldNotes1}"
# Escape single quotes for the SQL literal used below. Ampersand substitution is disabled in SQL*Plus.
sql_password="$(printf '%s' "$FIELD_NOTES_PASSWORD" | sed "s/'/''/g")"

sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF
SET ECHO OFF
ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
  user_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO user_count FROM dba_users WHERE username = 'FIELD_NOTES';
  IF user_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER FIELD_NOTES IDENTIFIED BY "' || REPLACE('${sql_password}', '"', '""') || '" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER FIELD_NOTES IDENTIFIED BY "' || REPLACE('${sql_password}', '"', '""') || '" ACCOUNT UNLOCK';
  END IF;
END;
/

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE TO FIELD_NOTES;
ALTER SESSION SET CURRENT_SCHEMA = FIELD_NOTES;

DECLARE
  object_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner = 'FIELD_NOTES' AND table_name = 'SITES';
  IF object_count = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE sites (
      site_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      site_code VARCHAR2(16) NOT NULL UNIQUE,
      site_name VARCHAR2(100) NOT NULL,
      region VARCHAR2(80) NOT NULL,
      latitude NUMBER(8,5),
      longitude NUMBER(8,5)
    )~';
  END IF;

  SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner = 'FIELD_NOTES' AND table_name = 'SPECIES';
  IF object_count = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE species (
      species_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      species_code VARCHAR2(16) NOT NULL UNIQUE,
      common_name VARCHAR2(100) NOT NULL,
      scientific_name VARCHAR2(120) NOT NULL,
      conservation_status VARCHAR2(24) NOT NULL
        CHECK (conservation_status IN ('COMMON', 'WATCH', 'PROTECTED'))
    )~';
  END IF;

  SELECT COUNT(*) INTO object_count FROM dba_tables WHERE owner = 'FIELD_NOTES' AND table_name = 'SIGHTINGS';
  IF object_count = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE sightings (
      sighting_code VARCHAR2(20) PRIMARY KEY,
      site_id NUMBER NOT NULL REFERENCES sites(site_id),
      species_id NUMBER NOT NULL REFERENCES species(species_id),
      observed_at TIMESTAMP NOT NULL,
      individual_count NUMBER(5) NOT NULL CHECK (individual_count > 0),
      observation_method VARCHAR2(32) NOT NULL,
      field_note VARCHAR2(500)
    )~';
  END IF;
END;
/

MERGE INTO sites target
USING (
  SELECT 'COAST-01' site_code, 'Tidepool Point' site_name, 'Pacific Coast' region, 48.42000 latitude, -123.37000 longitude FROM dual
  UNION ALL
  SELECT 'FOREST-02', 'Cedar Ridge', 'Coastal Forest', 48.51000, -123.51000 FROM dual
  UNION ALL
  SELECT 'WETLAND-03', 'Heron Marsh', 'South Island Wetlands', 48.35000, -123.55000 FROM dual
) src
ON (target.site_code = src.site_code)
WHEN MATCHED THEN UPDATE SET
  site_name = src.site_name,
  region = src.region,
  latitude = src.latitude,
  longitude = src.longitude
WHEN NOT MATCHED THEN INSERT (site_code, site_name, region, latitude, longitude)
  VALUES (src.site_code, src.site_name, src.region, src.latitude, src.longitude);

MERGE INTO species target
USING (
  SELECT 'SEA-STAR' species_code, 'Ochre sea star' common_name, 'Pisaster ochraceus' scientific_name, 'COMMON' conservation_status FROM dual
  UNION ALL
  SELECT 'GREAT-BLUE', 'Great blue heron', 'Ardea herodias', 'COMMON' FROM dual
  UNION ALL
  SELECT 'SALMON', 'Coho salmon', 'Oncorhynchus kisutch', 'WATCH' FROM dual
) src
ON (target.species_code = src.species_code)
WHEN MATCHED THEN UPDATE SET
  common_name = src.common_name,
  scientific_name = src.scientific_name,
  conservation_status = src.conservation_status
WHEN NOT MATCHED THEN INSERT (species_code, common_name, scientific_name, conservation_status)
  VALUES (src.species_code, src.common_name, src.scientific_name, src.conservation_status);

MERGE INTO sightings target
USING (
  SELECT 'OBS-0001' sighting_code,
         (SELECT site_id FROM sites WHERE site_code = 'COAST-01') site_id,
         (SELECT species_id FROM species WHERE species_code = 'SEA-STAR') species_id,
         TIMESTAMP '2025-05-11 09:20:00' observed_at, 14 individual_count, 'TIDEPOOL_TRANSECT' observation_method,
         'Observed along the eastern pool edge.' field_note FROM dual
  UNION ALL
  SELECT 'OBS-0002',
         (SELECT site_id FROM sites WHERE site_code = 'FOREST-02'),
         (SELECT species_id FROM species WHERE species_code = 'GREAT-BLUE'), TIMESTAMP '2025-05-12 07:45:00', 2, 'POINT_COUNT',
         'Pair feeding near the creek.' FROM dual
  UNION ALL
  SELECT 'OBS-0003',
         (SELECT site_id FROM sites WHERE site_code = 'WETLAND-03'),
         (SELECT species_id FROM species WHERE species_code = 'SALMON'), TIMESTAMP '2025-05-13 16:10:00', 6, 'STREAM_SURVEY',
         'Juveniles visible in the shallow channel.' FROM dual
) src
ON (target.sighting_code = src.sighting_code)
WHEN MATCHED THEN UPDATE SET
  site_id = src.site_id,
  species_id = src.species_id,
  observed_at = src.observed_at,
  individual_count = src.individual_count,
  observation_method = src.observation_method,
  field_note = src.field_note
WHEN NOT MATCHED THEN INSERT
  (sighting_code, site_id, species_id, observed_at, individual_count, observation_method, field_note)
  VALUES (
    src.sighting_code,
    src.site_id,
    src.species_id,
    src.observed_at,
    src.individual_count,
    src.observation_method,
    src.field_note
  );

CREATE OR REPLACE VIEW site_sighting_summary AS
SELECT
  site.site_code,
  site.site_name,
  COUNT(sighting.sighting_code) AS observation_records,
  NVL(SUM(sighting.individual_count), 0) AS observed_individuals
FROM sites site
LEFT JOIN sightings sighting ON sighting.site_id = site.site_id
GROUP BY site.site_code, site.site_name;

COMMIT;
EXIT SUCCESS
SQL
